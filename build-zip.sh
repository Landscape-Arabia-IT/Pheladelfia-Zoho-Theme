#!/bin/sh
set -eu

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
CONFIG="$ROOT/template/template.conf"

if [ ! -f "$CONFIG" ]; then
  printf 'Missing theme manifest: %s\n' "$CONFIG" >&2
  exit 1
fi

VERSION=$(node -e '
const fs = require("node:fs");
const config = JSON.parse(fs.readFileSync(process.argv[1], "utf8"));
if (typeof config.version !== "string" || !/^\d+\.\d+\.\d+$/.test(config.version)) {
  throw new Error("template.conf must contain a semantic version.");
}
process.stdout.write(config.version);
' "$CONFIG")

# Merge per-language translation files (lang/*.js) into a single
# template/js/ph-i18n.js so Zoho loads one script. Each lang file sets
# window.PH_I18N.<code>; adding a language = adding lang/<code>.js.
I18N_DIR="$ROOT/lang"
I18N_OUT="$ROOT/template/js/ph-i18n.js"
if [ -d "$I18N_DIR" ]; then
  {
    printf '/* Generated by build-zip.sh — do not edit. Sources: lang/*.js */\n'
    printf 'window.PH_I18N = window.PH_I18N || {};\n'
    for f in "$I18N_DIR"/*.js; do
      [ -e "$f" ] || continue
      cat "$f"
    done
  } > "$I18N_OUT"
fi

ARCHIVE="$ROOT/Pheladelfia-Nursery-V${VERSION}-Upload.zip"
rm -f "$ARCHIVE"
(
  cd "$ROOT"
  zip -qr "$ARCHIVE" template
)
unzip -t "$ARCHIVE" >/dev/null
printf 'Created and verified: %s\n' "$ARCHIVE"
